package Training5;

public class Triright {
    public static void main(String[] args) {
        int n = 5;
        for (int i = 0; i < 5; i++) {
            for (int j = 5  ; j <= n-1 ; j++ ) {
                System.out.print("*");
            }
            System.out.println();
        }
    }
}
